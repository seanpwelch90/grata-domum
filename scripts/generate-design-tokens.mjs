import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const palettes = JSON.parse(
  fs.readFileSync(path.join(root, "contracts/design-tokens.json"), "utf8"),
);
const roles = Object.keys(palettes.default).sort();
if (
  JSON.stringify(roles) !==
  JSON.stringify(Object.keys(palettes.christmas).sort())
) {
  throw new Error("Built-in palettes must have identical semantic roles.");
}
for (const palette of Object.values(palettes)) {
  if (Object.values(palette).some((color) => !/^#[0-9A-F]{6}$/.test(color))) {
    throw new Error(
      "Design tokens must be opaque uppercase six-digit sRGB hex colors.",
    );
  }
}
const cases = roles
  .map((role) => {
    const normal = palettes.default[role];
    const christmas = palettes.christmas[role];
    return `        case "${role}":\n            return ${normal === christmas ? `"${normal}"` : `christmas ? "${christmas}" : "${normal}"`}`;
  })
  .join("\n");
const swift = `// Generated by scripts/generate-design-tokens.mjs. Edit contracts/design-tokens.json.\npublic enum WelcomeBookTokens {\n    public static func value(_ role: String, christmas: Bool = false) -> String {\n        switch role {\n${cases}\n        default:\n            return "${palettes.default.ink}"\n        }\n    }\n}\n`;
const destination = path.join(
  root,
  "clients/GrataDomumKit/Sources/GrataDomumKit/WelcomeBookTokens.swift",
);
if (process.argv.includes("--check")) {
  if (fs.readFileSync(destination, "utf8") !== swift) {
    throw new Error(
      "Swift design tokens differ from the manifest. Run node scripts/generate-design-tokens.mjs.",
    );
  }
} else {
  fs.writeFileSync(destination, swift);
}
